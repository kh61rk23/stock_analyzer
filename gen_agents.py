out_dir = "/home/claude/sector_agents_5a"
os.makedirs(out_dir, exist_ok=True)

TMPL = (
    "# ==============================================================\n"
    "# sector_agents/CODE_agent.py\n"
    "# NAME エージェント v1.0  （東証業種コード: CODE）\n"
    "# ==============================================================\n"
    "# 【分析対象企業】TICKERS_CMT\n"
    "# ==============================================================\n\n"
    "import sys\n"
    "from pathlib import Path\n\n"
    "_here = Path(__file__).parent\n"
    "if str(_here) not in sys.path:\n"
    "    sys.path.insert(0, str(_here.parent))\n\n"
    "from sector_agents.base_agent import (\n"
    "    fetch_financials, build_macro_signals, build_result\n"
    ")\n\n"
    'SECTOR_CODE  = "CODE"\n'
    'SECTOR_NAME  = "NAME"\n\n'
    "TARGET_TICKERS = TICKERS_REPR\n\n"
    'SECTOR_NOTE = """\n'
    "### NAME ポイント\n"
    "NOTE_LINES\n"
    '"""\n\n\n'
    "def run_analysis(sector_code: str, cfg) -> dict:\n"
    '    """\n'
    "    NAMEの分析を実行する。\n"
    "    stock_analyzer_main.py の run_sector_analysis() から動的ロードで呼ばれる。\n"
    '    """\n'
    "    print(f\"  🏭 [SECTOR_CODE_VAR] SECTOR_NAME_VAR 分析開始...\")\n\n"
    "    companies = fetch_financials(TARGET_TICKERS)\n"
    "    ok = sum(1 for c in companies if c.get(\"fetch_ok\"))\n"
    "    print(f\"    財務データ取得: {ok}/{len(TARGET_TICKERS)} 銘柄成功\")\n\n"
    "    macro_signals = build_macro_signals(SECTOR_CODE, cfg)\n"
    "    tw = sum(1 for s in macro_signals if s[\"signal\"] == \"tailwind\")\n"
    "    hw = sum(1 for s in macro_signals if s[\"signal\"] == \"headwind\")\n"
    "    print(f\"    マクロシグナル: 追い風 {tw}件 / 逆風 {hw}件\")\n\n"
    "    result = build_result(SECTOR_CODE, SECTOR_NAME, companies, macro_signals, cfg)\n"
    "    result[\"insight_text\"] += \"\\n\" + SECTOR_NOTE\n"
    "    result[\"sector_note\"]   = SECTOR_NOTE\n\n"
    "    print(f\"    ✅ SECTOR_NAME_VAR: スコア {result['composite_score']}点 / リスク {result['risk_level']}\")\n"
    "    return result\n\n\n"
    "if __name__ == \"__main__\":\n"
    "    import importlib.util\n"
    "    for p in [\"/content/config.py\", str(Path(__file__).parents[1] / \"config.py\")]:\n"
    "        if Path(p).exists():\n"
    "            spec = importlib.util.spec_from_file_location(\"config\", p)\n"
    "            cfg  = importlib.util.module_from_spec(spec)\n"
    "            spec.loader.exec_module(cfg)\n"
    "            break\n"
    "    result = run_analysis(SECTOR_CODE, cfg)\n"
    "    print(result[\"insight_text\"])\n"
)

for code, name, tickers, notes in AGENTS:
    src = (TMPL
        .replace("CODE",          code)
        .replace("NAME",          name)
        .replace("TICKERS_CMT",   " / ".join(tickers))
        .replace("TICKERS_REPR",  repr(tickers))
        .replace("NOTE_LINES",    "\n".join(f"- {n}" for n in notes))
        .replace("SECTOR_CODE_VAR",  "{SECTOR_CODE}")
        .replace("SECTOR_NAME_VAR",  "{SECTOR_NAME}")
    )
    with open(f"{out_dir}/{code}_agent.py", "w", encoding="utf-8") as f:
        f.write(src)

print(f"生成: {len(AGENTS)} ファイル")

errors = []
for fp in sorted(glob.glob(f"{out_dir}/*.py")):
    try:
        py_compile.compile(fp, doraise=True)
    except py_compile.PyCompileError as e:
        errors.append(f"{fp}: {e}")

if errors:
    for e in errors:
        print(f"  ERROR: {e}")
else:
    print(f"全 {len(AGENTS)} ファイル 構文OK")
